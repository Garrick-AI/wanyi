"""Generate en/index.html from index.html (same app, English by default). Run after every change to index.html."""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
s = (root / "index.html").read_text(encoding="utf-8")
def rep(a, b):
    global s
    assert a in s, a
    s = s.replace(a, b, 1)
rep('<html lang="zh-Hant">', '<html lang="en">')
rep('<head>\n', '<head>\n<base href="../">\n')
rep('<title>萬一手冊</title>', '<title>Just in Case Handbook｜萬一手冊</title>')
i = s.index('<meta name="description"'); j = s.index('>', i) + 1
s = s[:i] + '<meta name="description" content="Just in Case Handbook: answer one question at a time to record where your bank accounts, insurance, MPF and important documents are, plus your final wishes, and get a PDF handbook for your family. Answers stay on your device. Part 1 is free.">' + s[j:]
rep('<link rel="canonical" href="https://garrick-ai.github.io/wanyi/">', '<link rel="canonical" href="https://garrick-ai.github.io/wanyi/en/">')
rep('<meta name="apple-mobile-web-app-title" content="萬一手冊">', '<meta name="apple-mobile-web-app-title" content="Just in Case">')
(root / "en").mkdir(exist_ok=True)
s = s.replace('<head>\n', '<head>\n<!-- Generated by tools/build-en.py from index.html. Do not edit by hand. -->\n', 1)
(root / "en" / "index.html").write_text(s, encoding="utf-8")
print("en/index.html written")
